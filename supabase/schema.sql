-- 1. إنشاء جدول المدفوعات الواردة (incoming_payments)
CREATE TABLE IF NOT EXISTS public.incoming_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_phone VARCHAR(20) NULL,                        -- رقم هاتف المحول (يقبل NULL عند فشل الاستخراج)
    amount NUMERIC(12, 2) NULL,                           -- المبلغ المحول
    transaction_id VARCHAR(50) UNIQUE NULL,               -- رقم العملية (فريد لمنع تكرار تسجيل نفس التحويل)
    raw_message TEXT NOT NULL,                            -- نص الرسالة بالكامل كما وصل للهاتف
    device_id VARCHAR(100) NULL,                          -- معرف الجهاز الذي استقبل الرسالة (مثل Sales_Phone_1)
    status VARCHAR(20) NOT NULL DEFAULT 'unlinked'        -- الحالة: 'unlinked' | 'linked' | 'error'
        CHECK (status IN ('unlinked', 'linked', 'error')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()         -- وقت التسجيل
);

-- 2. إنشاء الفهارس (Indexes) لتسريع الاستعلامات والفلترة في لوحة التحكم
CREATE INDEX IF NOT EXISTS idx_incoming_payments_status
    ON public.incoming_payments (status);

CREATE INDEX IF NOT EXISTS idx_incoming_payments_sender_phone
    ON public.incoming_payments (sender_phone);

CREATE INDEX IF NOT EXISTS idx_incoming_payments_created_at
    ON public.incoming_payments (created_at DESC);

-- 3. دالة PostgreSQL RPC لاستقبال الرسالة من تطبيق الأندرويد واستخراج بياناتها بالـ Regex
--    تتعامل تلقائياً مع التكرار (ON CONFLICT) ومع الرسائل غير المطابقة (status = 'error')
CREATE OR REPLACE FUNCTION public.ingest_sms_payment(
    p_raw_message TEXT,
    p_device_id VARCHAR DEFAULT 'Android_Phone'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
    v_amount_str TEXT;
    v_amount NUMERIC(12, 2);
    v_sender_phone VARCHAR(20);
    v_transaction_id VARCHAR(50);
    v_is_valid BOOLEAN := FALSE;
    v_status VARCHAR(20);
    v_inserted_row public.incoming_payments;
BEGIN
    IF p_raw_message IS NULL OR btrim(p_raw_message) = '' THEN
        RAISE EXCEPTION 'نص الرسالة مطلوب ولا يمكن أن يكون فارغاً';
    END IF;

    -- استخراج البيانات باستخدام نفس تعبيرات الـ Regex المطلوبة:
    -- 1) المبلغ: /مبلغ\s*([\d.]+)\s*جنيه/
    v_amount_str := substring(p_raw_message FROM 'مبلغ\s*([\d.]+)\s*جنيه');
    -- 2) رقم المحول: /من\s*(01[0-9]{9})/
    v_sender_phone := substring(p_raw_message FROM 'من\s*(01[0-9]{9})');
    -- 3) رقم العملية: /رقم العملية\s*:\s*(\d+)/
    v_transaction_id := substring(p_raw_message FROM 'رقم العملية\s*:\s*(\d+)');

    IF v_amount_str IS NOT NULL AND v_sender_phone IS NOT NULL AND v_transaction_id IS NOT NULL THEN
        BEGIN
            v_amount := v_amount_str::NUMERIC(12, 2);
            v_is_valid := TRUE;
        EXCEPTION WHEN OTHERS THEN
            v_is_valid := FALSE;
        END;
    END IF;

    IF v_is_valid THEN
        v_status := 'unlinked';
    ELSE
        -- في حال فشل استخراج البيانات الأساسية نترك الحقول فارغة (NULL) وبحالة 'error' للمراجعة اليدوية
        v_amount := NULL;
        v_sender_phone := NULL;
        v_transaction_id := NULL;
        v_status := 'error';
    END IF;

    -- إدخال السجل مع تجاهل التكرار إذا كان رقم العملية مسجلاً مسبقاً
    INSERT INTO public.incoming_payments (
        sender_phone,
        amount,
        transaction_id,
        raw_message,
        device_id,
        status
    )
    VALUES (
        v_sender_phone,
        v_amount,
        v_transaction_id,
        p_raw_message,
        COALESCE(NULLIF(btrim(p_device_id), ''), 'Android_Phone'),
        v_status
    )
    ON CONFLICT (transaction_id) DO NOTHING
    RETURNING * INTO v_inserted_row;

    -- إذا لم يتم الإدخال بسبب تكرار رقم العملية (Duplicate)
    IF v_inserted_row.id IS NULL AND v_transaction_id IS NOT NULL THEN
        RETURN jsonb_build_object(
            'success', TRUE,
            'duplicate', TRUE,
            'transaction_id', v_transaction_id,
            'message', 'تم استلام هذه العملية مسبقاً'
        );
    END IF;

    RETURN jsonb_build_object(
        'success', TRUE,
        'duplicate', FALSE,
        'status', v_inserted_row.status,
        'data', to_jsonb(v_inserted_row)
    );
END;
$$;

-- 4. تفعيل صلاحيات الوصول عبر Data API وتفعيل Row Level Security (RLS)
ALTER TABLE public.incoming_payments ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.incoming_payments TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.incoming_payments_id_seq TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.ingest_sms_payment(TEXT, VARCHAR) TO anon, authenticated;

-- سياسات RLS للسماح لتطبيق الأندرويد ولوحة التحكم بالقراءة والإضافة والتحديث
DROP POLICY IF EXISTS "allow_read_incoming_payments" ON public.incoming_payments;
CREATE POLICY "allow_read_incoming_payments"
    ON public.incoming_payments
    FOR SELECT
    TO anon, authenticated
    USING (true);

DROP POLICY IF EXISTS "allow_insert_incoming_payments" ON public.incoming_payments;
CREATE POLICY "allow_insert_incoming_payments"
    ON public.incoming_payments
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

DROP POLICY IF EXISTS "allow_update_incoming_payments" ON public.incoming_payments;
CREATE POLICY "allow_update_incoming_payments"
    ON public.incoming_payments
    FOR UPDATE
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "allow_delete_incoming_payments" ON public.incoming_payments;
CREATE POLICY "allow_delete_incoming_payments"
    ON public.incoming_payments
    FOR DELETE
    TO anon, authenticated
    USING (true);

-- 5. تفعيل البث اللحظي (Supabase Realtime) على جدول incoming_payments
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'incoming_payments'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.incoming_payments;
    END IF;
END
$$;
